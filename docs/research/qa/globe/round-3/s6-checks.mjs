import { launch, sleep } from './cdp.mjs';
import fs from 'node:fs/promises';
const b = await launch({ port: 9371 });
const R = {};
await b.open('/europe/'); await b.globeReady(); await sleep(800);
const st = await b.stageRect();
const dk = await b.g('return g.mineAt(56.0, 9.3);');
await b.click(st.x + dk.x, st.y + dk.y); await sleep(3000);
R.denmark = await b.evaluate(`[...document.querySelectorAll('.world__card:not([hidden]) a, .world__card:not([hidden]) h3')].map(a => a.textContent + (a.href ? ' -> ' + new URL(a.href).pathname : ''))`);
await b.shot('s6-europe-denmark-click');
await b.open('/programmes/'); await b.globeReady(); await sleep(800);
const cl = await b.evaluate(`(() => { const c = [...document.querySelectorAll('.world__cluster:not([hidden])')].sort((a, b) => (b._members?.length || 0) - (a._members?.length || 0))[0]; const r = c.getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2, n: c.textContent }; })()`);
await b.click(cl.x, cl.y);
await sleep(6000);
R.group = { cl, state: await b.g('return { alt: g.view.alt, close: g.close.active, zoom: g.close.zoom };'), clusters: await b.evaluate(`[...document.querySelectorAll('.world__cluster:not([hidden])')].map(c => c.textContent)`), pins: await b.evaluate(`[...document.querySelectorAll('.world__pin:not([hidden])')].length`) };
await b.shot('s6-programmes-group-split');
R.logs = b.logs.filter((l) => !/READ-usage|Expected value to be of type number/.test(l));
await fs.writeFile(new URL('./s6-checks.json', import.meta.url), JSON.stringify(R, null, 1));
console.log(JSON.stringify(R, null, 1));
b.close(); process.exit(0);
